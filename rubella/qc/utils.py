import numpy as np
from rabies.analysis_pkg.analysis_math import dice_coefficient
from rabies.analysis_pkg.diagnosis_pkg.dataset_QC import threshold_top_percent


def get_group_stats(FC_map_dict, avg_type='median', top_percent=10):
    '''Compute group statistics for a dictionary of FC maps.

    Group statistics include t-stats, the group average, standard deviation, and percent
    overlap of thresholded maps.

    FC_map_dict: dictionary of FC maps, where keys are img_ids and values are 
        vectorized FC maps (e.g. generated by rubella.basic.seed_based_FC)
    '''
        
    avg_FC = get_avg(FC_map_dict, avg_type=avg_type)

    data_array = np.array([FC_map_dict[k] for k in FC_map_dict])
    std_FC = data_array.std(axis=0)

    n=data_array.shape[0]
    tstat_data = data_array.mean(axis=0)/(std_FC/np.sqrt(n))
    tstat_data[np.isnan(tstat_data)]=0

    percent_overlap = get_avg(FC_map_dict, avg_type='percent_overlap', top_percent=top_percent)

    return tstat_data, avg_FC, std_FC, percent_overlap

def get_dice_list(FC_map_dict, avg_FC=None, avg_type='median', top_percent=10, seed_mask_arr=None):
    '''Compute the Dice coefficient between the group FC map and each individual FC map.

    The Dice coefficient is computed between a group mask generated from the average FC
    map and individual masks generated from each FC map in the input dictionary.
    
    FC_map_dict: dictionary of FC maps, where keys are img_ids and values are 
        vectorized FC maps (e.g. generated by rubella.basic.seed_based_FC)

    seed_mask_arr: boolean array of the seed mask used for seed-based connectivity, 
        if relevant. If provided, the dice coefficient will be computed only for 
        voxels outside the seed mask.
    '''

    mask_l = get_threshold_masks(FC_map_dict, top_percent=top_percent)
    if avg_FC is None: # compute the average from the input data
        avg_FC = get_avg(FC_map_dict, avg_type=avg_type)
    threshold = threshold_top_percent(avg_FC, top_percent=top_percent)
    group_mask=np.abs(avg_FC)>=threshold # taking absolute values to include negative weights
    if seed_mask_arr is None:
        # create mask of zeros so that no voxel gets excluded
        seed_mask_arr = np.zeros(group_mask.shape).astype(bool)
    seed_mask_arr = seed_mask_arr.copy().astype(bool)
    dice_list = [dice_coefficient(group_mask[~seed_mask_arr],mask[~seed_mask_arr]) for mask in mask_l]
    return dice_list

def get_avg(FC_map_dict, avg_type='median', top_percent=10):
    data_array = np.array([FC_map_dict[k] for k in FC_map_dict])
    if avg_type=='median':
        avg_FC = np.median(data_array, axis=0)
    elif avg_type=='mean':
        avg_FC = data_array.mean(axis=0)
    elif avg_type=='percent_overlap':
        mask_l = get_threshold_masks(FC_map_dict, top_percent=top_percent)
        mask_l = np.array(mask_l)
        avg_FC = (mask_l.sum(axis=0)/mask_l.shape[0])*100    
    return avg_FC

def get_threshold_masks(FC_map_dict, top_percent=10):
    # generate a list of threshold masks for each FC map
    mask_l = []
    for k in FC_map_dict:
        threshold = threshold_top_percent(FC_map_dict[k], top_percent=top_percent)
        mask=np.abs(FC_map_dict[k])>=threshold # taking absolute values to include negative weights
        mask_l.append(mask)
    return mask_l
